package com.ridelink.fareservice.dto;

import com.ridelink.fareservice.model.FareStatus;
import io.swagger.v3.oas.annotations.media.Schema;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * Detailed response for a calculated final fare record.
 * Perfectly compatible with group client contracts (e.g. FareInfo).
 */
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
@Schema(description = "Response containing final fare calculation and stored record")
public class FareResponse {

    @Schema(description = "Unique fare record ID generated by MongoDB", example = "6612ab789c01")
    private String id;

    @Schema(description = "Stable ride identifier", example = "ride-101")
    private String rideId;

    @Schema(description = "Passenger user ID", example = "pass-001")
    private String passengerId;

    @Schema(description = "Driver user ID", example = "driver-001")
    private String driverId;

    @Schema(description = "Vehicle category applied", example = "CAR")
    private String vehicleType;

    @Schema(description = "Total final fare amount charged", example = "1050.00")
    private BigDecimal amount;

    @Schema(description = "Currency of the transaction", example = "LKR")
    private String currency;

    @Schema(description = "Distance in kilometres", example = "8.5")
    private Double distanceKm;

    @Schema(description = "Duration in minutes", example = "22.0")
    private Double durationMinutes;

    @Schema(description = "Base fare amount component", example = "200.00")
    private BigDecimal baseFare;

    @Schema(description = "Distance fare portion", example = "850.00")
    private BigDecimal distanceFare;

    @Schema(description = "Duration fare portion (if applicable)", example = "0.00")
    private BigDecimal durationFare;

    @Schema(description = "Vehicle multiplier applied", example = "1.0")
    private BigDecimal vehicleMultiplier;

    @Schema(description = "Fare status: ESTIMATED or CALCULATED", example = "CALCULATED")
    private FareStatus status;

    @Schema(description = "Detailed breakdown formula and calculation summary",
            example = "Base Fare: 200.00 LKR + Distance: 8.50 km @ 100.00 LKR/km = 1050.00 LKR")
    private String pricingBreakdown;

    @Schema(description = "Timestamp when the fare was calculated and saved")
    private LocalDateTime createdAt;
}
